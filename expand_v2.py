def feishu_create(title, content_text):
    clean = content_text.split("#")[0].strip() if "#" in content_text else content_text
    tmpf = tempfile.mktemp(suffix=".md")
    with open(tmpf, "w") as f:
        f.write(clean)
    try:
        r = subprocess.run([
            "bash", "-c",
            f'export PATH="/opt/homebrew/bin:$PATH"; cat "{tmpf}" | lark-cli docs +create --title "{title}" --content - --doc-format markdown --as user --format json'
        ], capture_output=True, text=True, timeout=30)
    finally:
        if os.path.exists(tmpf):
            os.unlink(tmpf)
    if r.returncode != 0:
        return None
    try:
        data = json.loads(r.stdout)
        return data.get("data", {}).get("document", {}).get("document_id", "")
    except:
        m = re.search(r'document_id["\s:]+"([^"]+)"', r.stdout)
        return m.group(1) if m else None

def feishu_insert(folder, token, img_num):
    r = subprocess.run([
        "bash", "-c",
        f'export PATH="/opt/homebrew/bin:$PATH"; cd "{BASE}/image-cards/{folder}"; lark-cli docs +media-insert --doc {token} --file ./{img_num:02d}-cover.png --as user'
    ], capture_output=True, text=True, timeout=60)
    return r.returncode == 0

def process_topic(num, folder, detail):
    ap = f"{BASE}/image-cards/{folder}/article.md"
    if not os.path.exists(ap):
        print(f"  article.md not found for {folder}")
        return None
    with open(ap) as f:
        current = f.read()
    
    clean = current.split("#")[0] if "#" in current else current
    base_chars = len(clean.replace("\n", "").replace(" ", ""))
    
    # Build new article: existing body + new detail
    tags_part = ""
    if "#" in current:
        tags = "".join("#" + t.strip() for t in current.split("#")[1:])
        tags_part = "\n\n" + tags
    
    new_body = clean.rstrip() + "\n\n" + detail
    new_article = new_body
    
    new_chars = len(new_article.replace("\n", "").replace(" ", "").split("#")[0])
    
    print(f"  Topic {num} ({folder}): {base_chars} -> {new_chars} chars")
    
    # Write updated file
    with open(ap, "w") as f:
        f.write(new_article)
    
    # Check images
    imgs = [i for i in range(1, 7) if os.path.exists(f"{BASE}/image-cards/{folder}/{i:02d}-cover.png")]
    if len(imgs) < 6:
        print(f"  WARNING: only {len(imgs)}/6 images")
        return None
    
    # Get title from first line
    first_line = new_article.split("\n")[0].strip()
    # Truncate if contains #
    first_line = first_line.split("#")[0].strip()
    title = f"场景{num}：{first_line[:50]}"
    
    token = feishu_create(title, new_article)
    if not token:
        print(f"  Feishu create FAILED")
        return None
    
    for i in range(1, 7):
        ok = feishu_insert(folder, token, i)
        if not ok:
            print(f"  Insert {i} FAILED")
        time.sleep(3)
    
    print(f"  Feishu: https://qcnh2b60jsx1.feishu.cn/docx/{token}")
    return token

