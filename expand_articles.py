def feishu_create(title, content_text):
    clean = content_text.split("#")[0].strip() if "#" in content_text else content_text
    tmpf = tempfile.mktemp(suffix=".md")
    with open(tmpf, "w") as f:
        f.write(clean)
    try:
        r = subprocess.run([
            "bash", "-c",
            f'export PATH="/opt/homebrew/bin:$PATH"; cat "{tmpf}" | lark-cli docs +create --title "{title}" --content - --doc-format markdown --as user --format json'
        ], capture_output=True, text=True, timeout=30)
    finally:
        if os.path.exists(tmpf):
            os.unlink(tmpf)
    if r.returncode != 0:
        return None
    try:
        data = json.loads(r.stdout)
        return data.get("data", {}).get("document", {}).get("document_id", "")
    except:
        m = re.search(r'document_id["\s:]+"([^"]+)"', r.stdout)
        return m.group(1) if m else None

def feishu_insert(folder, token, img_num):
    r = subprocess.run([
        "bash", "-c",
        f'export PATH="/opt/homebrew/bin:$PATH"; cd "{BASE}/image-cards/{folder}"; lark-cli docs +media-insert --doc {token} --file ./{img_num:02d}-cover.png --as user'
    ], capture_output=True, text=True, timeout=60)
    return r.returncode == 0

def build_article(num, title_line, short_body, detail_text):
    """Build ~800 char article."""
    # First line as scene title
    scene_title = f"场景{num}：{title_line}"
    
    # The body: use short_body as intro, then detail_text for expansion
    lines = [l.strip() for l in short_body.split("\n") if l.strip()]
    intro = "\n".join(lines[:3]) if lines else ""
    
    # Build final
    body = intro + "\n\n" + detail_text
    
    # Add tags
    if "#" in short_body:
        tags = "".join("#" + t.strip() for t in short_body.split("#")[1:])
        if tags.lower() not in body.lower():
            body += "\n\n" + tags.strip()
    
    return scene_title, body

