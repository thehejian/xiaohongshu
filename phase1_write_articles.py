def find_expansion(title, body):
    for keywords, text in EXPANSIONS:
        for kw in keywords:
            if kw in title or kw in body[:100]:
                return text
    return "历史从来不只是王侯将相的舞台。那些看不见的制度、被忽略的日常、压在普通人肩上的重担——当这些碎片拼在一起，你才看到真正的时代模样。"

def expand_article(num, title_line, short_body):
    """Expand short article to ~800 chars"""
    first_line = short_body.split("\n")[0].strip()
    if not first_line:
        first_line = title_line

    # Handle #tags at end
    tags = ""
    if "#" in short_body:
        body_clean = short_body.split("#")[0].strip()
        tags = "".join("#" + t.strip() for t in short_body.split("#")[1:])
    else:
        body_clean = short_body

    expansion = find_expansion(title_line, body_clean)

    # Build expanded article
    expanded = body_clean + "\n\n" + expansion

    # Trim to ~750-850 chars
    if len(expanded) > 900:
        expanded = expanded[:850].rsplit("。", 1)[0] + "。"

    # Add tags
    if tags:
        expanded += "\n\n" + tags.strip()

    return first_line, expanded

