for block in blocks:
    m = re.match(r'## 主题 (\d+)[：:]?\s*(.*?)\n', block)
    if not m:
        continue
    num = int(m.group(1))
    if num < 43 or num > 100:
        continue
    title_line = m.group(2).strip()

    fm = re.search(r'\*\*文件夹\*\*:\s*\x60(.+?)\x60', block)
    folder = fm.group(1) if fm else f'topic-{num:03d}'

    am = re.search(r'### 正文\n(.*?)\n### 提示词', block, re.DOTALL)
    article_short = am.group(1).strip() if am else ""

    pm = re.findall(r'\d+\.\s*\*\*(.+?)\*\*[：:]\s*(.+)', block)

    # Create directory
    workdir = f"{BASE}/image-cards/{folder}"
    os.makedirs(f"{workdir}/prompts", exist_ok=True)

    # Write article
    title, article_text = expand_article(num, title_line, article_short)
    with open(f"{workdir}/article.md", "w") as f:
        f.write(article_text)

    # Write prompts
    for i, (label, prompt) in enumerate(pm):
        num_img = i + 1
        fname = f"{workdir}/prompts/{num_img:02d}-cover.md"
        with open(fname, "w") as f:
            f.write(prompt)

    print(f"TOPIC {num:3d} | {folder:35s} | article={len(article_text):4d}chars | 6 prompts OK")
